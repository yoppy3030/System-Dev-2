      <h2>2. Business Cards (名刺交換 - Meishi Kōkan)</h2>
      <p>Offer and receive cards with both hands. Read the card before putting it away respectfully in a cardholder, not your pocket.</p>
    </div>

    <div class="info-block">
      <h2>3. Punctuality</h2>
      <p>Being 5–10 minutes early is ideal. Always notify if running late and apologize sincerely.</p>
    </div>

    <div class="info-block">
      <h2>4. Attire and Appearance</h2>
      <p>Dark suits and modest dress are expected. Visible tattoos and flashy accessories may be frowned upon.</p>
    </div>

    <div class="info-block">
      <h2>5. Communication Style</h2>
      <p>Be indirect and polite. Avoid open confrontation. Non-verbal cues and listening attentively are important.</p>
    </div>

    <div class="info-block">
      <h2>6. Hierarchy and Formality</h2>
      <p>Always respect rank and seniority. Use formal titles like "-san" and avoid calling superiors by first names.</p>
    </div>

    <div class="info-block">
      <h2>7. Gift Giving</h2>
      <p>Choose small, well-wrapped, thoughtful gifts. Avoid giving in sets of four or overly expensive items.</p>
    </div>

    <div class="info-block">
      <h2>8. After-Work Socializing (飲み会 - Nomikai)</h2>
      <p>Drinking together strengthens workplace relationships. Pour drinks for others and know your limits.</p>
    </div>

    <div class="info-block">
      <h2>9. Decision Making</h2>
      <p>Expect group-based decisions and longer processes. Patience is a virtue.</p>
    </div>

    <div class="info-block">
      <h2>10. Handling Mistakes</h2>
      <p>Own up, apologize sincerely using phrases like "mōshiwake arimasen," and take responsibility.</p>
