      <div class="advice-grid">
        <div class="advice-card">
          <h4>🔍 Search Strategy</h4>
          <ul>
            <li data-translate>Use both English and Japanese keywords when searching.</li>
            <li data-translate>Build a bilingual resume to unlock more opportunities.</li>
            <li data-translate>Check visa restrictions: Not all jobs are available to every visa type.</li>
            <li data-translate>Follow up after applying—especially for small companies.</li>
          </ul>
        </div>
        
        <div class="advice-card">
          <h4>📝 Application Tips</h4>
          <ul>
            <li data-translate>Customize your resume for each application.</li>
            <li data-translate>Include a photo in your Japanese resume (履歴書).</li>
            <li data-translate>Prepare for traditional Japanese interviews.</li>
            <li data-translate>Network through professional events and meetups.</li>
          </ul>
        </div>
        
        <div class="advice-card">
          <h4>⏰ Timing</h4>
          <ul>
            <li data-translate>Japanese companies often hire in April (new graduates) and September.</li>
            <li data-translate>Start your job search 3-6 months before your desired start date.</li>
            <li data-translate>Be aware of Golden Week and Obon holiday periods.</li>
            <li data-translate>Many companies have hiring freezes during fiscal year-end (March).</li>
