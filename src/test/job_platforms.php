    <section id="reading-tips" class="section">
      <h2 data-translate>🔍 Tips for Reading Japanese Job Listings</h2>
      <div class="tips-grid">
        <div class="tip-card">
          <h4>雇用形態 (Employment Type)</h4>
          <ul>
            <li><strong>正社員 (Seishain):</strong> Full-time permanent employee</li>
            <li><strong>契約社員 (Keiyaku Shain):</strong> Contract employee</li>
            <li><strong>アルバイト (Arubaito):</strong> Part-time worker</li>
            <li><strong>派遣社員 (Haken Shain):</strong> Temporary worker</li>
          </ul>
        </div>
        
        <div class="tip-card">
          <h4>給与 (Salary)</h4>
          <ul>
            <li><strong>月収 (Gesshu):</strong> Monthly salary</li>
            <li><strong>年収 (Nenshu):</strong> Annual salary</li>
            <li><strong>時給 (Jikyuu):</strong> Hourly wage</li>
            <li><strong>基本給 (Kihonkyuu):</strong> Base salary</li>
          </ul>
        </div>
        
        <div class="tip-card">
          <h4>勤務時間 (Work Hours)</h4>
          <ul>
            <li><strong>定時 (Teiji):</strong> Regular hours</li>
            <li><strong>残業 (Zangyou):</strong> Overtime</li>
            <li><strong>フレックスタイム (Furekku Taimu):</strong> Flextime</li>
            <li><strong>リモートワーク (Rimo-to Wa-ku):</strong> Remote work</li>
          </ul>
        </div>
        
        <div class="tip-card">
          <h4>日本語レベル (Japanese Level)</h4>
          <ul>
            <li><strong>N1:</strong> Native-like proficiency</li>
            <li><strong>N2:</strong> Business Japanese</li>
            <li><strong>N3:</strong> Daily conversation</li>
            <li><strong>N4/N5:</strong> Basic Japanese</li>
          </ul>
        </div>
      </div>
    </section>

