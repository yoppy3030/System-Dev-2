      <h2>🌐 Recommended Job Search Websites</h2>
      <ul>
        <li><strong><a href="https://www.gaijinpot.com/jobs/" target="_blank">GaijinPot</a>:</strong> Best for English speakers. Offers jobs in IT, teaching, hospitality, and more.</li>
        <li><strong><a href="https://www.daijob.com/" target="_blank">Daijob</a>:</strong> Great for bilingual professionals. Includes high-level business roles.</li>
        <li><strong><a href="https://jobsinjapan.com/" target="_blank">Jobs in Japan</a>:</strong> English teaching, part-time, and contract jobs.</li>
        <li><strong><a href="https://hello-work.go.jp/" target="_blank">Hello Work</a>:</strong> Government employment service. Often requires Japanese, but very comprehensive.</li>
        <li><strong><a href="https://jp.indeed.com/" target="_blank">Indeed Japan</a>:</strong> Aggregated listings for almost all industries.</li>
      </ul>
    </section>

    <section class="section">
      <h2>🔍 Tips for Reading Japanese Job Listings</h2>
      <ul>
        <li><strong>雇用形態 (Employment Type):</strong> 正社員 = Full-time, アルバイト = Part-time</li>
        <li><strong>給与 (Salary):</strong> 表示が月収 (monthly) か年収 (yearly) か確認</li>
        <li><strong>勤務時間 (Work Hours):</strong> 長時間労働に注意</li>
        <li><strong>日本語レベル:</strong> N1〜N5で求められる語学力が違う</li>
      </ul>
    </section>

    <section class="section">
      <h2>🧭 Choosing the Right Platform for You</h2>
      <ul>
        <li><strong>Beginners in Japan:</strong> Try GaijinPot or Jobs in Japan for English listings.</li>
        <li><strong>JLPT N2 or higher:</strong> Expand your search with Indeed Japan or Hello Work.</li>
        <li><strong>Career Professionals:</strong> Daijob and LinkedIn often list bilingual corporate jobs.</li>
        <li><strong>Students/Part-time Seekers:</strong> Use Baitoru or TownWork (requires some Japanese).</li>
      </ul>
    </section>

    <section class="section">
      <h2>🧠 Bonus Advice</h2>
      <ul>
        <li>Use both English and Japanese keywords when searching.</li>
        <li>Build a bilingual resume to unlock more opportunities.</li>
        <li>Check visa restrictions: Not all jobs are available to every visa type.</li>
        <li>Follow up after applying—especially for small companies.</li>
      </ul>
    </section>

